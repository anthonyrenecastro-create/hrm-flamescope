function download(name: string, content: string, type = 'application/json') {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement('a');
  a.href = url; a.download = name; a.click();
  URL.revokeObjectURL(url);
}

function datasetToCsv(ds: CombustionDataset): string {
  const head = 'id,source_identifier,campaign,date,fuel,o2,n2,co2,he,pressure_kpa,d0_mm,extinction_diameter_mm,burning_rate_mm2s,burn_time_s,outcome,data_kind,source_url';
  const rows = ds.experiments.map((e) => [
    e.id, e.sourceIdentifier, e.campaign, e.dateISO ?? '', e.fuel,
    e.oxidizer.o2 ?? '', e.oxidizer.n2 ?? '', e.oxidizer.co2 ?? '', e.oxidizer.he ?? '',
    e.pressureKPa ?? '', e.initialDiameterMm ?? '', e.extinctionDiameterMm ?? '',
    e.burningRateMm2PerS ?? '', e.burnTimeS ?? '', e.outcome, e.provenance.kind, e.provenance.sourceUrl,
  ].join(','));
  return [head, ...rows].join('\n');
}

function pythonScript(ds: CombustionDataset): string {
  return `"""FlameScope reproducible analysis export
Dataset: ${ds.id} (${ds.kind}) — ${ds.title}
Source: ${ds.sourceUrl}
Generated by HRM FlameScope. Reproduces the burning-rate summary and the
held-out comparison task definition used by the app (graph model code is
TypeScript in src/engine/combustionModel.ts; this script reproduces the
dataset statistics and the per-fuel means exactly, and states the split
rule so the comparison can be re-implemented faithfully).
"""
import csv, hashlib, statistics

rows = list(csv.DictReader(open("flamescope_dataset.csv")))
by_fuel = {}
for r in rows:
    if r["burning_rate_mm2s"]:
        by_fuel.setdefault(r["fuel"], []).append(float(r["burning_rate_mm2s"]))
for fuel, ks in sorted(by_fuel.items()):
    print(fuel, "n=", len(ks), "mean K=", round(statistics.mean(ks), 4), "mm^2/s")

# Deterministic split (matches app): hash of id with seed 42, test if h % 100 < 25
def is_test(exp_id, seed=42):
    h = seed
    for ch in exp_id:
        h = (h * 31 + ord(ch)) & 0xFFFFFFFF
    return h % 100 < 25
print("test ids:", [r["id"] for r in rows if is_test(r["id"])][:10])
`;
}

