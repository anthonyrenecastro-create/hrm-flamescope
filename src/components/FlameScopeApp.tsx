function ExperimentCard({ e }: { e: CombustionExperiment }) {
  const row = (label: string, value: string) => (
    <div className="flex justify-between border-b border-slate-800/60 py-1"><span className="text-slate-400">{label}</span><span>{value}</span></div>
  );
  const fmt = (v: number | null, unit: string, digits = 2) => (v === null ? 'missing (not zero)' : `${v.toFixed(digits)} ${unit}`);
  return (
    <div className="bg-slate-900/60 border border-slate-800 rounded-lg p-4 text-sm">
      <h3 className="font-semibold mb-2">{e.id} · CIR identifier {e.sourceIdentifier || '—'}</h3>
      {row('Campaign', e.campaign)}
      {row('Date', e.dateISO ?? 'not reported')}
      {row('Fuel', e.fuel)}
      {row('Gravity', e.gravity)}
      {row('O2 mole fraction', e.oxidizer.o2 === null ? 'missing' : e.oxidizer.o2.toFixed(2))}
      {row('Diluents', `CO2 ${e.oxidizer.co2 ?? '—'} · He ${e.oxidizer.he ?? '—'} · N2 ${e.oxidizer.n2 ?? '—'}`)}
      {row('Pressure', fmt(e.pressureKPa, 'kPa', 1))}
      {row('Initial diameter D0', fmt(e.initialDiameterMm, 'mm'))}
      {row('Extinction diameter', fmt(e.extinctionDiameterMm, 'mm'))}
      {row('Burning rate K', fmt(e.burningRateMm2PerS, 'mm²/s', 3))}
      {row('Burn time', fmt(e.burnTimeS, 's', 1))}
      {row('Outcome', e.outcome)}
      <p className="mt-2 text-xs text-slate-400">
        Provenance: {e.provenance.kind} · {e.provenance.institution} ·{' '}
        <a className="text-orange-300 underline" href={e.provenance.sourceUrl} target="_blank" rel="noreferrer">{e.provenance.datasetId}</a>
        {e.missingFields.length > 0 && <><br />Missing fields: {e.missingFields.join(', ')}</>}
      </p>
    </div>
  );
}

function TrajectoryChart({ traj, extD }: { traj: Array<{ tS: number; diameterMm: number }>; extD: number | null }) {
  const W = 520, H = 240, P = 34;
  const tMax = traj[traj.length - 1].tS;
  const dMax = traj[0].diameterMm * 1.08;
  const x = (t: number) => P + (t / tMax) * (W - 2 * P);
  const y = (d: number) => H - P - (d / dMax) * (H - 2 * P);
  const path = traj.map((p, i) => `${i === 0 ? 'M' : 'L'}${x(p.tS).toFixed(1)},${y(p.diameterMm).toFixed(1)}`).join(' ');
  return (
    <svg viewBox={`0 0 ${W} ${H}`} className="w-full">
      <rect x={P} y={P} width={W - 2 * P} height={H - 2 * P} fill="#0b1220" stroke="#1e293b" />
      <path d={path} fill="none" stroke="#fb923c" strokeWidth={2} />
      {extD !== null && <circle cx={x(tMax)} cy={y(extD)} r={4} fill="#f87171" />}
      <text x={P} y={H - 8} fill="#94a3b8" fontSize={10}>time (s) → {tMax.toFixed(1)}</text>
      <text x={4} y={P - 8} fill="#94a3b8" fontSize={10}>diameter (mm), max {dMax.toFixed(1)}</text>
      {extD !== null && <text x={x(tMax) - 130} y={y(extD) - 8} fill="#f87171" fontSize={10}>reported extinction diameter</text>}
    </svg>
  );
}

function NetworkPanel({ ds, subset, selectedId, onSelect }: {
  ds: CombustionDataset;
  subset: CombustionExperiment[];
  selectedId: string;
  onSelect: (id: string) => void;
}) {
  const graph = useMemo(() => buildRelationshipGraph(subset), [subset]);
  const W = 900, H = 460;
  const pos = subset.map((_, i) => {
    const angle = (i / Math.max(1, subset.length)) * Math.PI * 2;
    const ring = 0.32 + 0.55 * ((i * 7919) % 10) / 10;
    return { x: W / 2 + Math.cos(angle) * (W / 2 - 50) * ring, y: H / 2 + Math.sin(angle) * (H / 2 - 40) * ring };
  });
  return (
    <section>
      <p className="text-sm text-slate-300 mb-2 max-w-3xl">
        Showing {subset.length} experiments (filters apply). Edges are declared similarity relations — shared fuel,
        comparable conditions, same test date. <b>Edges are not physical energy transport.</b> Node color: fuel. Click a node to inspect it.
      </p>
      <svg viewBox={`0 0 ${W} ${H}`} className="w-full bg-slate-900/40 border border-slate-800 rounded-lg">
        {graph.edges.slice(0, 400).map((e, i) => (
          <line key={i} x1={pos[e.a].x} y1={pos[e.a].y} x2={pos[e.b].x} y2={pos[e.b].y} stroke="#334155" strokeOpacity={0.25 + e.weight * 0.5} />
        ))}
        {subset.map((e, i) => (
          <circle key={e.id} cx={pos[i].x} cy={pos[i].y} r={e.id === selectedId ? 7 : 4.5}
            fill={e.fuel.toLowerCase().includes('heptane') ? '#38bdf8' : '#fb923c'}
            stroke={e.id === selectedId ? '#fff' : 'none'} strokeWidth={1.5}
            className="cursor-pointer" onClick={() => onSelect(e.id)}>
            <title>{e.id} — {e.fuel} — O2 {e.oxidizer.o2 ?? '—'} — {e.outcome}</title>
          </circle>
        ))}
      </svg>
      <p className="text-xs text-slate-500 mt-1">Dataset: {ds.title} · graph semantics: {graph.semantics}</p>
    </section>
  );
}

